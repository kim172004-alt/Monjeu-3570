import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

OUT = Path('/home/user/worldcraft/tests/results')
OUT.mkdir(exist_ok=True)
records = []

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for mode, viewport in [('desktop', {'width':1440,'height':1000}), ('mobile', {'width':390,'height':844})]:
        context = browser.new_context(viewport=viewport)
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto('http://localhost:4200/')
        def screen(n):
            expect(page.locator('[data-screen]')).to_have_count(1)
            expect(page.locator('[data-screen]')).to_have_attribute('data-screen', str(n))
            expect(page.locator('[data-screen]')).to_have_css('opacity', '1')
            assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Horizontal overflow'
            records.append({'mode':mode,'screen':n,'only_one_mounted':True})
        screen(1)
        expect(page.get_by_role('button',name='COMMENCER')).to_be_disabled()
        page.get_by_role('textbox',name='Nom du personnage').fill('Camille')
        page.screenshot(path=str(OUT / f'{mode}-accueil.png'), full_page=True)
        page.get_by_role('button',name='COMMENCER').click()
        screen(2)
        expect(page.get_by_role('textbox',name='Nom du personnage')).to_have_value('Camille')
        page.get_by_label('Genre',exact=True).select_option('Non-binaire')
        page.get_by_label('Apparence',exact=True).select_option('Douce')
        page.get_by_role('button',name='Peau 4',exact=True).click()
        page.get_by_role('button',name='Cheveux 4',exact=True).click()
        page.get_by_label('Coiffure',exact=True).select_option('Bouclés')
        page.get_by_label('Vêtements',exact=True).select_option('Tunique')
        page.get_by_role('button',name='Élégant',exact=True).click()
        page.get_by_role('button',name='CONTINUER',exact=True).click()
        screen(3)
        expect(page.locator('.world-card')).to_have_count(5)
        expect(page.get_by_role('button',name='CONTINUER',exact=True)).to_be_disabled()
        page.get_by_role('button',name='VILLAGE AGRICOLE & NATURE',exact=False).click()
        page.screenshot(path=str(OUT / f'{mode}-univers.png'), full_page=True)
        page.get_by_role('button',name='CONTINUER',exact=True).click()
        screen(4)
        expect(page.locator('.destiny-grid .choice')).to_have_count(20)
        expect(page.get_by_role('button',name='CONTINUER',exact=True)).to_be_disabled()
        page.get_by_role('button',name='Scientifique',exact=True).click()
        page.get_by_role('button',name='RETOUR',exact=True).click()
        screen(3)
        expect(page.get_by_role('button',name='VILLAGE AGRICOLE & NATURE',exact=False)).to_have_attribute('aria-pressed','true')
        page.get_by_role('button',name='CONTINUER',exact=True).click()
        screen(4)
        expect(page.get_by_role('button',name='Scientifique',exact=True)).to_have_attribute('aria-pressed','true')
        page.get_by_role('button',name='CONTINUER',exact=True).click()
        screen(5)
        expect(page.get_by_role('button',name='CONTINUER',exact=True)).to_be_disabled()
        page.get_by_role('button',name='Amitié',exact=True).click()
        page.get_by_role('button',name='Mystère',exact=True).click()
        page.get_by_role('button',name='CONTINUER',exact=True).click()
        screen(6)
        expect(page.locator('dl')).to_contain_text('Camille')
        expect(page.locator('dl')).to_contain_text('VILLAGE AGRICOLE & NATURE')
        expect(page.locator('dl')).to_contain_text('Scientifique')
        expect(page.locator('dl')).to_contain_text('Amitié')
        expect(page.locator('dl')).to_contain_text('Mystère')
        page.screenshot(path=str(OUT / f'{mode}-resume.png'), full_page=True)
        page.get_by_role('button',name='MODIFIER',exact=True).click()
        screen(2)
        expect(page.get_by_label('Genre',exact=True)).to_have_value('Non-binaire')
        expect(page.get_by_label('Apparence',exact=True)).to_have_value('Douce')
        expect(page.get_by_label('Coiffure',exact=True)).to_have_value('Bouclés')
        page.get_by_role('textbox',name='Nom du personnage').fill('Camille Rose')
        for n in [3,4,5,6]:
            page.get_by_role('button',name='CONTINUER',exact=True).click()
            screen(n)
        expect(page.locator('dl')).to_contain_text('Camille Rose')
        page.get_by_role('button',name='ENTRER DANS MON MONDE',exact=True).click()
        screen(7)
        expect(page.get_by_text('Votre monde se construit...',exact=True)).to_be_visible()
        expect(page.locator('input,select,.progress')).to_have_count(0)
        expect(page.locator('[data-screen="8"]')).to_be_visible(timeout=6000)
        screen(8)
        expect(page.locator('input,select,.progress')).to_have_count(0)
        expect(page.locator('.player-name')).to_have_text('Camille Rose')
        for command in ['Menu','Personnage','Inventaire','Construire','Interaction','Nova']:
            page.get_by_role('button',name=command,exact=True).click()
            expect(page.locator('.game-panel')).to_be_visible()
            panel_box = page.locator('.game-panel').bounding_box()
            assert panel_box['height'] < viewport['height'] * .5
            page.get_by_role('button',name='Fermer le panneau',exact=True).click()
            expect(page.locator('.game-panel')).to_have_count(0)
        page.screenshot(path=str(OUT / f'{mode}-jeu.png'), full_page=True)
        page.go_back()
        screen(6)
        page.reload()
        screen(6)
        expect(page.locator('dl')).to_contain_text('Camille Rose')
        saved = page.evaluate("JSON.parse(localStorage.getItem('worldcraft-character'))")
        assert saved['skin']=='#a67350' and saved['hair']=='#c2a166'
        assert saved['destiny']=='Scientifique' and saved['stories']==['Amitié','Mystère']
        assert not errors, errors
        records.append({'mode':mode,'browser_back':True,'reload_persistence':True,'runtime_errors':errors})
        context.close()
    # Edge cases: narrow mobile, each return, editing an empty name, canceled load.
    context = browser.new_context(viewport={'width':320,'height':700})
    page = context.new_page()
    page.goto('http://localhost:4200/jeu')
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','2')
    name = page.get_by_role('textbox',name='Nom du personnage')
    name.fill('Zoé')
    name.fill('')
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','2')
    expect(page.get_by_role('button',name='CONTINUER',exact=True)).to_be_disabled()
    name.fill('Zoé')
    page.get_by_role('button',name='RETOUR',exact=True).click()
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','1')
    page.get_by_role('button',name='COMMENCER').click()
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='RETOUR',exact=True).click()
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','2')
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='CITÉ FUTURISTE',exact=False).click()
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='Artiste',exact=True).click()
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='RETOUR',exact=True).click()
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','4')
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='Drame',exact=True).click()
    page.get_by_role('button',name='Drame',exact=True).click()
    expect(page.get_by_role('button',name='CONTINUER',exact=True)).to_be_disabled()
    page.get_by_role('button',name='Romance',exact=True).click()
    page.get_by_role('button',name='CONTINUER',exact=True).click()
    page.get_by_role('button',name='ENTRER DANS MON MONDE',exact=True).click()
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','7')
    page.get_by_role('button',name='RETOUR',exact=True).click()
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','6')
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    # An assertion on location after a browser-side one-shot timeout proves the loading effect was canceled.
    page.evaluate('() => new Promise(resolve => setTimeout(resolve, 2100))')
    expect(page.locator('[data-screen]')).to_have_attribute('data-screen','6')
    records.append({'mode':'narrow-mobile','viewport':'320x700','route_guard':True,'empty_name_edit':True,'style_deselection':True,'loading_cancellation':True})
    context.close()
    browser.close()
OUT.joinpath('navigation.json').write_text(json.dumps(records,indent=2,ensure_ascii=False))
print(json.dumps({'status':'PASS','checks':len(records),'viewports':['1440x1000','390x844']},ensure_ascii=False))